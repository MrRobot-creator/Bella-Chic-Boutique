  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'bella-chic-products'
    and (select public.is_store_admin())
  )
  with check (
    bucket_id = 'bella-chic-products'
    and (select public.is_store_admin())
  );

drop policy if exists "Store admins can delete product images" on storage.objects;
