create table if not exists public.catalog_products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  description text not null,
  price numeric(10, 2) not null check (price > 0),
  old_price numeric(10, 2),
  image text not null,
  images jsonb not null default '[]'::jsonb,
  sizes jsonb not null default '[]'::jsonb,
  size_fit text,
  colors jsonb not null default '[]'::jsonb,
  tag text,
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.catalog_products
  add column if not exists images jsonb not null default '[]'::jsonb;

alter table public.catalog_products
  add column if not exists size_fit text;

create table if not exists public.store_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.catalog_products enable row level security;
alter table public.store_admins enable row level security;

create or replace function public.is_store_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.store_admins
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_store_admin() from public;
grant execute on function public.is_store_admin() to authenticated;

grant usage on schema public to anon, authenticated;
grant select on public.catalog_products to anon, authenticated;
grant insert, update, delete on public.catalog_products to authenticated;
grant select on public.store_admins to authenticated;
grant usage, select on sequence public.catalog_products_id_seq to authenticated;

drop policy if exists "Catalog is publicly readable" on public.catalog_products;
create policy "Catalog is publicly readable"
  on public.catalog_products for select
  to anon, authenticated
  using (true);

drop policy if exists "Store admins can manage catalog" on public.catalog_products;
create policy "Store admins can manage catalog"
  on public.catalog_products for all
  to authenticated
  using ((select public.is_store_admin()))
  with check ((select public.is_store_admin()));

drop policy if exists "Admins can read their own access" on public.store_admins;
create policy "Admins can read their own access"
  on public.store_admins for select
  to authenticated
  using (user_id = (select auth.uid()));

