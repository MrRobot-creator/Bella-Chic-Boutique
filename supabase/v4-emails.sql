    v_cta_label := 'Avaliar minhas peças';
    v_cta_url := v_site || '/avaliar/' || p_order.review_token::text;
  elsif p_event = 'cancelled' then
    v_subject := 'Pedido ' || p_order.reference || ' cancelado';
    v_title := 'Pedido cancelado';
    v_pre := 'O pedido ' || p_order.reference || ' foi cancelado.';
    v_body := '<p style="margin:0 0 10px;">' || v_hello || ' O pedido <b>' || public.html_escape(p_order.reference) || '</b> foi cancelado.</p>'
