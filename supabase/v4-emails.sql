-- Conteúdo de cada etapa do pedido. Devolve { subject, html } ou null quando não há e-mail para a etapa.
create or replace function public.order_email_content(p_order public.store_orders, p_event text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_settings public.store_settings%rowtype;
  v_unit public.store_units%rowtype;
  v_site text;
  -- Só o primeiro nome, só com letras: o campo é digitado pela cliente.
  v_first text := left(regexp_replace(split_part(btrim(coalesce(p_order.customer->>'name', '')), ' ', 1), '[^[:alpha:]]', '', 'g'), 20);
  v_hello text;
  v_total numeric := greatest(0, p_order.subtotal - p_order.discount) + coalesce((p_order.fulfillment->>'deliveryFee')::numeric, 0);
  v_items text;
  v_summary text;
  v_pix text := '';
  v_where text;
  v_store_whats text := regexp_replace(coalesce(p_order.unit->>'storePhone', ''), '\D', '', 'g');
  v_subject text;
  v_title text;
  v_pre text;
  v_body text;
  v_cta_label text;
  v_cta_url text;
