create or replace function public.html_escape(p_text text)
returns text
language sql
immutable
set search_path = ''
as $$
  select replace(replace(replace(replace(replace(coalesce(p_text, ''), '&', '&amp;'), '<', '&lt;'), '>', '&gt;'), '"', '&quot;'), '''', '&#39;');
$$;

create or replace function public.brl(p_value numeric)
returns text
language sql
immutable
set search_path = ''
as $$
  select 'R$ ' || replace(replace(replace(to_char(coalesce(p_value, 0), 'FM999,999,990.00'), ',', '#'), '.', ','), '#', '.');
$$;

create or replace function public.pix_text(p_text text, p_max integer)
returns text
language sql
immutable
set search_path = ''
as $$
  select left(btrim(regexp_replace(regexp_replace(
    translate(coalesce(p_text, ''), 'áàâãäéèêëíìîïóòôõöúùûüçñÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑ', 'aaaaaeeeeiiiiooooouuuucnAAAAAEEEEIIIIOOOOOUUUUCN'),
    '[^A-Za-z0-9 .,@/-]', '', 'g'), '\s+', ' ', 'g')), p_max);
$$;

create or replace function public.pix_crc16(p_payload text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_bytes bytea := convert_to(p_payload, 'UTF8');
  v_crc integer := 65535;
  v_index integer;
  v_bit integer;
begin
  for v_index in 0 .. length(v_bytes) - 1 loop
    v_crc := v_crc # (get_byte(v_bytes, v_index) << 8);
    for v_bit in 1 .. 8 loop
      if (v_crc & 32768) <> 0 then
        v_crc := ((v_crc << 1) # 4129) & 65535;
      else
        v_crc := (v_crc << 1) & 65535;
      end if;
    end loop;
  end loop;
  return upper(lpad(to_hex(v_crc), 4, '0'));
end;
$$;

-- Pix copia e cola (mesmo formato de src/utils/pix.ts).
create or replace function public.pix_payload(p_key text, p_name text, p_city text, p_amount numeric, p_txid text)
returns text
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_payload text;
  v_ref text := coalesce(nullif(left(regexp_replace(coalesce(p_txid, ''), '[^A-Za-z0-9]', '', 'g'), 25), ''), '***');
  v_name text := coalesce(nullif(public.pix_text(p_name, 25), ''), 'Loja');
  v_city text := coalesce(nullif(public.pix_text(p_city, 15), ''), 'Brasil');
  v_account text := '0014br.gov.bcb.pix' || '01' || lpad(length(btrim(p_key))::text, 2, '0') || btrim(p_key);
begin
  v_payload := '000201'
    || '26' || lpad(length(v_account)::text, 2, '0') || v_account
    || '52040000' || '5303986'
    || case when coalesce(p_amount, 0) > 0
         then '54' || lpad(length(to_char(p_amount, 'FM999999990.00'))::text, 2, '0') || to_char(p_amount, 'FM999999990.00')
         else '' end
    || '5802BR'
    || '59' || lpad(length(v_name)::text, 2, '0') || v_name
    || '60' || lpad(length(v_city)::text, 2, '0') || v_city
    || '62' || lpad((4 + length(v_ref))::text, 2, '0') || '05' || lpad(length(v_ref)::text, 2, '0') || v_ref
    || '6304';
  return v_payload || public.pix_crc16(v_payload);
end;
$$;

