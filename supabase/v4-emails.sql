      || '<p style="margin:0;">Se quiser, a gente te ajuda a escolher outra peça.</p>';
  else
    return null;
  end if;

  return jsonb_build_object(
    'subject', v_subject,
    'html', public.email_layout(v_title, v_pre, v_body, v_cta_label, v_cta_url, v_site)
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- Envio pelo Resend (assíncrono, pelo pg_net)
-- ---------------------------------------------------------------------------

create or replace function public.send_order_email(p_order_id uuid, p_event text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.store_orders%rowtype;
  v_settings public.store_settings%rowtype;
  v_email text;
  v_content jsonb;
  v_key text;
  v_request bigint;
  v_log_id bigint;
begin
  select * into v_settings from public.store_settings where id = 1;
  if not coalesce(v_settings.order_emails_enabled, false) or v_settings.email_from is null then
    return;
  end if;

  select * into v_order from public.store_orders where id = p_order_id;
  if not found or v_order.channel <> 'site' then
    return;
  end if;
  v_email := nullif(lower(btrim(coalesce(v_order.customer->>'email', ''))), '');
  if v_email is null or v_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' then
    return;
  end if;

  v_content := public.order_email_content(v_order, p_event);
  if v_content is null then
    return;
  end if;

  insert into public.email_log (order_id, event, to_email, subject)
  values (v_order.id, p_event, v_email, v_content->>'subject')
  on conflict (order_id, event) do nothing
  returning id into v_log_id;
  if v_log_id is null then
    return; -- já enviado para esta etapa
  end if;

  begin
    select decrypted_secret into v_key from vault.decrypted_secrets where name = 'resend_api_key' limit 1;
    if v_key is null then
      raise exception 'Chave do Resend não encontrada no cofre (resend_api_key)';
    end if;
    v_request := net.http_post(
      url := 'https://api.resend.com/emails',
      body := jsonb_strip_nulls(jsonb_build_object(
        'from', v_settings.email_from,
        'to', jsonb_build_array(v_email),
        'subject', v_content->>'subject',
        'html', v_content->>'html',
        'reply_to', v_settings.email_reply_to,
        'tags', jsonb_build_array(jsonb_build_object('name', 'etapa', 'value', p_event))
      )),
      headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || v_key),
      timeout_milliseconds := 10000
    );
    update public.email_log set request_id = v_request where id = v_log_id;
  exception when others then
    update public.email_log set error = left(sqlerrm, 300) where id = v_log_id;
  end;
end;
$$;

create or replace function public.order_email_trigger()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  begin
    if tg_op = 'INSERT' and new.status = 'pending' then
      perform public.send_order_email(new.id, 'recebido');
    elsif tg_op = 'UPDATE' and new.status is distinct from old.status
      and new.status in ('confirmed', 'paid', 'shipped', 'delivered', 'cancelled') then
      perform public.send_order_email(new.id, new.status);
    end if;
  exception when others then
    -- E-mail nunca impede o pedido.
    null;
  end;
  return new;
end;
$$;

-- Roda no fim da transação, quando o pedido já tem estoque reservado e frete calculado.
drop trigger if exists order_email_trigger on public.store_orders;
create constraint trigger order_email_trigger
  after insert or update of status on public.store_orders
  deferrable initially deferred
  for each row execute function public.order_email_trigger();

