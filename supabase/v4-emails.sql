      v_title := 'Seu pedido saiu para entrega';
      v_pre := 'O pedido ' || p_order.reference || ' está a caminho.';
      v_body := '<p style="margin:0 0 10px;">' || v_hello || ' O pedido <b>' || public.html_escape(p_order.reference) || '</b> está a caminho.</p><p style="margin:0;font-size:13px;color:#7A6567;">' || v_where || '</p>';
