      || '<td align="right" style="padding:10px 0;border-bottom:1px solid #F4E4E7;font-size:14px;color:#3E2A2E;white-space:nowrap;">'
      || public.brl((i.value->>'unitPrice')::numeric * (i.value->>'quantity')::integer) || '</td></tr>',
