      v_subject := 'Seu pedido está pronto para retirar';
      v_title := 'Pronto para retirar';
      v_pre := 'O pedido ' || p_order.reference || ' está esperando por você.';
      v_body := '<p style="margin:0 0 10px;">' || v_hello || ' O pedido <b>' || public.html_escape(p_order.reference) || '</b> está pronto. Te esperamos!</p><p style="margin:0;font-size:13px;color:#7A6567;">' || v_where || '</p>';
    end if;
  elsif p_event = 'delivered' then
    v_subject := 'Conta pra gente o que achou das suas peças';
    v_title := 'Esperamos que você ame!';
    v_pre := 'Avalie suas peças da Bella Chic.';
    v_body := '<p style="margin:0 0 10px;">' || v_hello || ' Seu pedido <b>' || public.html_escape(p_order.reference) || '</b> foi entregue.</p>'
