    raise exception 'Invalid email';
  end if;
  select * into v_settings from public.store_settings where id = 1;
  if v_settings.email_from is null then
    raise exception 'Missing sender';
  end if;
  select decrypted_secret into v_key from vault.decrypted_secrets where name = 'resend_api_key' limit 1;
  if v_key is null then
    raise exception 'Missing Resend key';
  end if;

  v_sample.reference := 'BC-TESTE000000000';
  v_sample.status := 'pending';
  v_sample.channel := 'site';
  v_sample.unit_id := 'galeria-portuense';
  v_sample.customer := jsonb_build_object('name', 'Cliente Teste', 'phone', '', 'email', btrim(p_to));
  v_sample.items := '[{"name":"Vestido Dress","size":"U","color":"Rosa","quantity":1,"unitPrice":75}]'::jsonb;
  v_sample.unit := '{"name":"Galeria Portuense","address":"Tv. Padre Eutíquio, 1055 - Batista Campos","storePhone":"5591980648559"}'::jsonb;
  v_sample.fulfillment := '{"type":"Entrega","street":"Rua Exemplo","houseNumber":"10","neighborhood":"Batista Campos","deliveryCity":"Belém","deliveryFee":12}'::jsonb;
  v_sample.payment := 'Pix';
  v_sample.subtotal := 75;
  v_sample.discount := 0;
  v_sample.stock_taken := true;
  v_sample.reserved_until := now() + interval '2 hours';
  v_sample.review_token := gen_random_uuid();

  v_content := public.order_email_content(v_sample, 'recebido');
  perform net.http_post(
    url := 'https://api.resend.com/emails',
    body := jsonb_strip_nulls(jsonb_build_object(
      'from', v_settings.email_from,
      'to', jsonb_build_array(btrim(p_to)),
      'subject', '[Teste] ' || (v_content->>'subject'),
      'html', v_content->>'html',
      'reply_to', v_settings.email_reply_to
    )),
    headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || v_key),
    timeout_milliseconds := 10000
  );
  return 'ok';
end;
$$;

-- Últimos e-mails enviados, com a resposta do Resend (para /admin › Configurações).
create or replace function public.recent_order_emails(p_limit integer default 20)
returns table (
  id bigint, reference text, event text, to_email text, subject text,
  created_at timestamptz, status_code integer, error text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not (select public.is_store_owner()) then
    raise exception 'Not authorized';
  end if;
  if to_regclass('net._http_response') is null then
    return query
      select l.id, o.reference, l.event, l.to_email, l.subject, l.created_at, null::integer, l.error
      from public.email_log l left join public.store_orders o on o.id = l.order_id
      order by l.created_at desc
      limit least(greatest(coalesce(p_limit, 20), 1), 100);
  else
    return query execute
      'select l.id, o.reference, l.event, l.to_email, l.subject, l.created_at, r.status_code::integer,
              coalesce(l.error, case when r.status_code >= 400 then left(r.content::text, 300) end, r.error_msg::text)
       from public.email_log l
       left join public.store_orders o on o.id = l.order_id
       left join net._http_response r on r.id = l.request_id
       order by l.created_at desc
       limit $1'
      using least(greatest(coalesce(p_limit, 20), 1), 100);
  end if;
end;
$$;

