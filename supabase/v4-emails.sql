    then 'Entrega em ' || public.html_escape(concat_ws(', ',
      nullif(p_order.fulfillment->>'street', '') || coalesce(' ' || nullif(p_order.fulfillment->>'houseNumber', ''), ''),
      nullif(p_order.fulfillment->>'neighborhood', ''), nullif(p_order.fulfillment->>'deliveryCity', '')))
    else 'Retirada na ' || public.html_escape(p_order.unit->>'name') || coalesce(' (' || public.html_escape(nullif(p_order.unit->>'address', '')) || ')', '')
  end;

