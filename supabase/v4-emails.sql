      || case when p_order.stock_taken and p_order.reserved_until is not null
           then ' e separamos suas peças até <b>' || to_char(p_order.reserved_until at time zone 'America/Belem', 'HH24"h"MI "de" DD/MM') || '</b>' else '' end
      || '. A atendente vai confirmar tudo com você pelo WhatsApp.</p>' || v_summary || v_pix;
  elsif p_event = 'confirmed' then
    v_subject := 'Pedido ' || p_order.reference || ' confirmado';
    v_title := 'Seu pedido está confirmado';
    v_pre := 'Tudo certo com o pedido ' || p_order.reference || '.';
    v_body := '<p style="margin:0 0 10px;">' || v_hello || ' Confirmamos seu pedido <b>' || public.html_escape(p_order.reference) || '</b>. Obrigada por escolher a Bella Chic!</p>' || v_summary || v_pix;
