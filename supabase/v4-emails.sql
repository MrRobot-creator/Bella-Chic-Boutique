  and (email_reply_to is null or (length(email_reply_to) <= 160 and email_reply_to ~ '^[^\s@]+@[^\s@]+\.[^\s@]+$'))
  and (site_url is null or (length(site_url) <= 200 and site_url ~ '^https://[^\s/]+$'))
);

